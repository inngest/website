#!/usr/bin/env node
/**
 * Pulls the "Build for the lonng run" artwork out of the long-run pages
 * for the 12 Days workflow cards (/12-days/card), so the cards use the
 * campaign's real vectors rather than a redraw:
 *
 *   - the mouth and green tongue (from /long-run, with its runner removed)
 *   - the runners: NYC's pizza slice, SF's coffee cup, and /long-run's
 *     running Inngest logo, each cropped to its own SVG
 *   - Savannah's running rat from the 12 Days art (a PNG, embedded as is)
 *
 * The pages server-render their RunningFriend SVG in its starting pose,
 * so this reads that markup from a running dev server and writes
 * components/v1/pages/WorkflowCards/art.generated.ts.
 *
 * Usage (with `pnpm dev` running on :3001):
 *   node scripts/generate-workflow-card-art.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";

const HOST = process.env.HOST ?? "http://localhost:3001";
const OUT = "components/v1/pages/WorkflowCards/art.generated.ts";

/**
 * Runner crops, in the scene's artwork units, measured with getBBox() on
 * each runner's pose group (shadows included) plus a little padding.
 */
const RUNNERS = {
  pizza: { page: "/nyc-long-run", box: [965, 150, 218, 192] },
  cup: { page: "/sf-long-run", box: [982, 158, 166, 196] },
  logo: { page: "/long-run", box: [967, 156, 155, 186] },
};
const PAD = 6;

/** The scene's <svg>…</svg> from a page's HTML. */
function sceneSvg(html) {
  const at = html.indexOf('viewBox="0 0 1738 499"');
  if (at < 0) throw new Error("RunningFriend SVG not found");
  const start = html.lastIndexOf("<svg", at);
  return html.slice(start, matchingClose(html, start, "svg"));
}

/** Index just past the tag that closes the one opened at `start`. */
function matchingClose(s, start, tag) {
  const re = new RegExp(`<${tag}\\b|</${tag}>`, "g");
  re.lastIndex = start;
  let depth = 0;
  for (let m; (m = re.exec(s)); ) {
    depth += m[0].startsWith("</") ? -1 : 1;
    if (depth === 0) return re.lastIndex;
  }
  throw new Error(`unclosed <${tag}>`);
}

/** Splits an element's inner markup into its top-level children. */
function children(inner) {
  const out = [];
  let i = 0;
  while (i < inner.length) {
    const open = inner.indexOf("<", i);
    if (open < 0) break;
    const tag = /^<([a-zA-Z]+)/.exec(inner.slice(open))[1];
    const selfClosing = /^<[^>]*\/>/.test(inner.slice(open));
    const end = selfClosing
      ? inner.indexOf(">", open) + 1
      : matchingClose(inner, open, tag);
    out.push({ tag, markup: inner.slice(open, end) });
    i = end;
  }
  return out;
}

const innerOf = (el) => el.slice(el.indexOf(">") + 1, el.lastIndexOf("</"));

async function load(page) {
  const res = await fetch(HOST + page);
  if (!res.ok) throw new Error(`${page}: ${res.status}`);
  const svg = sceneSvg(await res.text());
  const parts = children(innerOf(svg));
  const defs = parts.filter((p) => p.tag === "defs").map((p) => p.markup);
  const groups = parts.filter((p) => p.tag === "g");
  // The runner is the last top-level group: rotate(…) › translate(…) ›
  // the pose group, which is what we keep.
  const runnerOuter = groups[groups.length - 1];
  const pose = children(
    innerOf(children(innerOf(runnerOuter.markup))[0].markup)
  )[0].markup;
  const scene = parts
    .filter((p) => p !== runnerOuter)
    .map((p) => p.markup)
    .join("");
  return { scene, pose, defs: defs.join("") };
}

const wrap = (viewBox, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="none">${body}</svg>`;

const out = {};
for (const [id, { page, box }] of Object.entries(RUNNERS)) {
  const { scene, pose, defs } = await load(page);
  const [x, y, w, h] = box;
  out[id] = {
    svg: wrap(
      `${x - PAD} ${y - PAD} ${w + PAD * 2} ${h + PAD * 2}`,
      pose + defs
    ),
    width: w + PAD * 2,
    height: h + PAD * 2,
  };
  if (id === "logo") out.scene = wrap("0 0 1738 499", scene);
}

const b64 = (s) => Buffer.from(s).toString("base64");

// Savannah's running rat from the 12 Days art. It's a flat image on the
// campaign salmon (#F55C50), which is also the card's background, so it
// needs no cutout.
const RAT = "public/assets/v1/12-days/cards/rat.png";
const rat = readFileSync(RAT);
const ts = `// Generated by scripts/generate-workflow-card-art.mjs — do not edit.
// The "Build for the lonng run" campaign art, as SVG data URIs.

export const SCENE = {
  src: "data:image/svg+xml;base64,${b64(out.scene)}",
  width: 1738,
  height: 499,
};

export const RUNNER_ART = {
${["pizza", "cup", "logo"]
  .map(
    (id) => `  ${id}: {
    src: "data:image/svg+xml;base64,${b64(out[id].svg)}",
    width: ${out[id].width},
    height: ${out[id].height},
  },`
  )
  .join("\n")}
  rat: {
    src: "data:image/png;base64,${rat.toString("base64")}",
    width: 820,
    height: 286,
  },
} as const;
`;
writeFileSync(OUT, ts);
console.log(`wrote ${OUT} (${Math.round(ts.length / 1024)} KB)`);
